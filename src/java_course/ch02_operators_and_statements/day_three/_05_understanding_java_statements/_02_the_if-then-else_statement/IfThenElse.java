if(hourOfDay < 11) {
System.out.println("Good Morning");
} else if(hourOfDay < 15) {
System.out.println("Good Afternoon");
} else {
System.out.println("Good Evening");
}

/*
 * La declaración if-then-else permite ejecutar diferentes bloques de código 
 * dependiendo de la condición que se cumpla. 
 * En este caso, si hourOfDay es menor que 11, se imprimirá "Good Morning". 
 * Si no, pero hourOfDay es menor que 15, se imprimirá "Good Afternoon". 
 * Si ninguna de las condiciones anteriores se cumple, se imprimirá "Good Evening".
*/