//La conversión de sistema numérico es:
System.out.println(56); // Decimal (base 10), se imprime tal cual: 56
System.out.println(0b11); //  Binario (base 2), 0b indica binario. 11 en binario = 3 en decimal. 
System.out.println(017); // Octal (base 8), el prefijo 0 indica octal. 1×8 + 7 = 15.
System.out.println(0x1F); // Hexadecimal (base 16), el prefijo 0x indica hexadecimal. 1×16 + 15 = 31.