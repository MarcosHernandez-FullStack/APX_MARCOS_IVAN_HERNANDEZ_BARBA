/*Los constructores determinados se crean cuando no se especifica algún constructor en la clase,
 * Java crea uno automáticamente, este método no cuenta con argumentos.
 */
class Rabbit1 {
}
class Rabbit2 {
public Rabbit2() { }
}
class Rabbit3 {
public Rabbit3(boolean b) { }
}
class Rabbit4 {
private Rabbit4() { }
}

/*
 * Rabbit1 es la única clase que tiene un constructor predeterminado. 
 */