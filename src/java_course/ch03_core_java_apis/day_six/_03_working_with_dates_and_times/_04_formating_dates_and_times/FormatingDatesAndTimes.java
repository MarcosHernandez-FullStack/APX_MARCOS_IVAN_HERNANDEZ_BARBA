LocalDate date = LocalDate.of(2020, Month.JANUARY, 20);
System.out.println(date.getDayOfWeek()); // Obtiene el día de la semana, respuesta: MONDAY
System.out.println(date.getMonth()); // Obtiene el mes, respuesta: JANUARY
System.out.println(date.getYear()); // Obtiene el año, respuesta: 2020
System.out.println(date.getDayOfYear()); // Obtiene el día del año, respuesta: 20